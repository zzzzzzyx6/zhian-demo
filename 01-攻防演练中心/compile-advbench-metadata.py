"""Compile local provenance and scene labels without changing source questions."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
DEST = ROOT / 'dataset-sources' / 'AdvBench'
annotation = json.loads((DEST / 'scene-annotations.json').read_text(encoding='utf-8'))
provenance = json.loads((DEST / 'provenance.json').read_text(encoding='utf-8'))
text = (ROOT / 'src' / 'bank-data.js').read_text(encoding='utf-8-sig')
questions = json.loads(text[text.index('['):text.rindex(']') + 1])
ids = [qid for group in annotation['groups'].values() for qid in group]
assert len(ids) == len(set(ids)) == len(questions) == 520
assert set(ids) == {q['id'] for q in questions}
assert provenance['sha256'] == annotation['sourceSha256']
provenance['sceneAnnotation'] = {k: v for k, v in annotation.items() if k != 'groups'}
js = '// Generated by compile-advbench-metadata.py; source questions are unchanged.\n'
js += 'window.AdvBenchProvenance=' + json.dumps(provenance, ensure_ascii=False, separators=(',', ':')) + ';\n'
js += '(function(){const groups=' + json.dumps(annotation['groups'], separators=(',', ':')) + ';\n'
js += 'const tags=new Map(Object.entries(groups).flatMap(([scene,ids])=>ids.map(id=>[id,scene])));\n'
js += "for(const q of window.AdvBenchData){q.sceneTags=[tags.get(q.id)];q.sceneTagOrigin='platform-annotation';q.sceneTagVersion=1;q.sceneAnnotation={scheme:'platform-common-v1',version:'2026-10-19',method:'AI辅助逐题归类',reviewStatus:'平台固定标签'};}})();\n"
(ROOT / 'src' / 'advbench-metadata.js').write_text(js, encoding='utf-8')
print(f'Compiled metadata for {len(ids)} questions; original questions unchanged.')
